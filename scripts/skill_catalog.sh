#!/bin/bash
# Generate docs/skills.md and one OpenCode /<skill> command per skill from each SKILL.md frontmatter.
# Usage: ./scripts/skill_catalog.sh [--check]
#   (none)   rewrite docs/skills.md and the generated OpenCode commands
#   --check  exit non-zero when either is out of date

set -euo pipefail
# Glob order follows the locale; C keeps the catalog identical on macOS and Linux.
export LC_ALL=C

DOTFILES_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
SKILLS_DIR="$DOTFILES_DIR/stow/opencode/skills"
MANIFEST="$SKILLS_DIR/.skill-sources.tsv"
CATALOG="$DOTFILES_DIR/docs/skills.md"
# OpenCode loads skills with @skill-id, not /skill-id; these commands give it Claude Code's slash form.
COMMANDS_DIR="$DOTFILES_DIR/stow/opencode/.config/opencode/commands"
COMMAND_MARKER="# Generated by scripts/skill_catalog.sh; edit the skill, not this file."

RED='\033[0;31m'
GREEN='\033[0;32m'
NC='\033[0m'

# Prints name, invocation, and a one-line description, tab-separated.
# Folded (>) and literal (|) descriptions are joined into one line.
frontmatter() {
    awk '
        NR == 1 && $0 == "---" { inside = 1; next }
        inside && $0 == "---" { exit }
        !inside { next }
        block && /^[[:space:]]*$/ { next }
        block && /^[[:space:]]/ {
            line = $0
            sub(/^[[:space:]]+/, "", line)
            description = description (description == "" ? "" : " ") line
            next
        }
        { block = 0 }
        /^name:/ { name = $0; sub(/^name:[[:space:]]*/, "", name) }
        /^disable-model-invocation:[[:space:]]*true/ { manual = 1 }
        /^description:/ {
            value = $0
            sub(/^description:[[:space:]]*/, "", value)
            if (value ~ /^[>|][-+]?$/) { block = 1; description = "" }
            else { gsub(/^"|"$/, "", value); description = value }
        }
        END {
            printf "%s\t%s\t%s\n", name, (manual ? "you" : "you or agents"), description
        }
    ' "$1"
}

owner_of() {
    awk -F '\t' -v skill="$1" '$1 == skill { print $2; found = 1; exit } END { if (!found) print "not recorded" }' "$MANIFEST"
}

render() {
    printf '<!-- Generated by scripts/skill_catalog.sh from each SKILL.md; edit the skills, not this file. -->\n\n'
    printf '# Skills\n\n'
    printf 'Every skill in `stow/opencode/skills/`, linked into `~/.agents/skills/` and `~/.claude/skills/`.\n'
    printf '"Invoked by: you" means the skill only runs when you type its name; "you or agents" means agents can also start it from its description.\n'
    printf 'Owner comes from `.skill-sources.tsv`; see [CONTEXT.md](../CONTEXT.md) for the terms.\n\n'
    printf '| Skill | Invoked by | Owner | What it does |\n'
    printf '| --- | --- | --- | --- |\n'
    local skill_md
    for skill_md in "$SKILLS_DIR"/*/SKILL.md; do
        local dir_name
        dir_name="$(basename "$(dirname "$skill_md")")"
        local name invocation description
        IFS=$'\t' read -r name invocation description < <(frontmatter "$skill_md")
        description="${description//|/\\|}"
        printf '| [`%s`](../stow/opencode/skills/%s/SKILL.md) | %s | %s | %s |\n' \
            "${name:-$dir_name}" "$dir_name" "$invocation" "$(owner_of "$dir_name")" "$description"
    done
}

yaml_string() {
    local value=$1
    value="${value//\\/\\\\}"
    value="${value//\"/\\\"}"
    printf '"%s"' "$value"
}

render_command() {
    local skill_md=$1
    local dir_name name invocation description
    dir_name="$(basename "$(dirname "$skill_md")")"
    IFS=$'\t' read -r name invocation description < <(frontmatter "$skill_md")
    printf -- '---\n%s\ndescription: %s\n---\n' "$COMMAND_MARKER" "$(yaml_string "$description")"
    printf 'Load the `%s` skill with the skill tool and follow it.\n\n$ARGUMENTS\n' "$dir_name"
}

# Writes the expected commands into a directory, so --check can diff it against the tracked one.
render_commands() {
    local out_dir=$1
    local skill_md
    mkdir -p "$out_dir"
    for skill_md in "$SKILLS_DIR"/*/SKILL.md; do
        render_command "$skill_md" > "$out_dir/$(basename "$(dirname "$skill_md")").md"
    done
}

# Only marked files are ours; hand-written commands in the same directory are left alone.
generated_commands() {
    local dir=$1
    local file
    for file in "$dir"/*.md; do
        if [ -f "$file" ] && sed -n 2p "$file" | grep -qxF "$COMMAND_MARKER"; then
            printf '%s\n' "$file"
        fi
    done
}

write_commands() {
    local file
    while IFS= read -r file; do
        rm "$file"
    done < <(generated_commands "$COMMANDS_DIR")
    render_commands "$COMMANDS_DIR"
}

commands_current() {
    local expected
    local file
    expected="$(mktemp -d)"
    render_commands "$expected"
    local status=0
    while IFS= read -r file; do
        if [ ! -f "$expected/$(basename "$file")" ]; then
            status=1
        fi
    done < <(generated_commands "$COMMANDS_DIR")
    for file in "$expected"/*.md; do
        if ! diff -q "$file" "$COMMANDS_DIR/$(basename "$file")" >/dev/null 2>&1; then
            status=1
        fi
    done
    rm -rf "$expected"
    return "$status"
}

case "${1:-}" in
    "")
        render > "$CATALOG"
        write_commands
        printf "${GREEN}[skills]${NC} wrote %s and %s\n" "${CATALOG#"$DOTFILES_DIR"/}" "${COMMANDS_DIR#"$DOTFILES_DIR"/}"
        ;;
    --check)
        if ! diff -u "$CATALOG" <(render) >/dev/null 2>&1; then
            printf "${RED}[skills]${NC} docs/skills.md is out of date; run ./scripts/skill_catalog.sh\n" >&2
            exit 1
        fi
        if ! commands_current; then
            printf "${RED}[skills]${NC} OpenCode skill commands are out of date; run ./scripts/skill_catalog.sh\n" >&2
            exit 1
        fi
        printf "${GREEN}[skills]${NC} docs/skills.md and OpenCode skill commands are up to date\n"
        ;;
    *)
        sed -n '2,5p' "$0" >&2
        exit 2
        ;;
esac
