#!/bin/bash
# Generate docs/skills.md from each skill's SKILL.md frontmatter and .skill-sources.tsv.
# Usage: ./scripts/skill_catalog.sh [--check]
#   (none)   rewrite docs/skills.md
#   --check  exit non-zero when docs/skills.md is out of date

set -euo pipefail

DOTFILES_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"
SKILLS_DIR="$DOTFILES_DIR/stow/claude/.claude/skills"
MANIFEST="$SKILLS_DIR/.skill-sources.tsv"
CATALOG="$DOTFILES_DIR/docs/skills.md"

RED='\033[0;31m'
GREEN='\033[0;32m'
NC='\033[0m'

# Prints name, invocation, and a one-line description, tab-separated.
# Folded (>) and literal (|) descriptions are joined into one line.
frontmatter() {
    awk '
        NR == 1 && $0 == "---" { inside = 1; next }
        inside && $0 == "---" { exit }
        !inside { next }
        block && /^[[:space:]]*$/ { next }
        block && /^[[:space:]]/ {
            line = $0
            sub(/^[[:space:]]+/, "", line)
            description = description (description == "" ? "" : " ") line
            next
        }
        { block = 0 }
        /^name:/ { name = $0; sub(/^name:[[:space:]]*/, "", name) }
        /^disable-model-invocation:[[:space:]]*true/ { manual = 1 }
        /^description:/ {
            value = $0
            sub(/^description:[[:space:]]*/, "", value)
            if (value ~ /^[>|][-+]?$/) { block = 1; description = "" }
            else { gsub(/^"|"$/, "", value); description = value }
        }
        END {
            printf "%s\t%s\t%s\n", name, (manual ? "you" : "you or agents"), description
        }
    ' "$1"
}

owner_of() {
    awk -F '\t' -v skill="$1" '$1 == skill { print $2; found = 1; exit } END { if (!found) print "not recorded" }' "$MANIFEST"
}

render() {
    printf '<!-- Generated by scripts/skill_catalog.sh from each SKILL.md; edit the skills, not this file. -->\n\n'
    printf '# Skills\n\n'
    printf 'Every skill in `stow/claude/.claude/skills/`, linked into `~/.agents/skills/` and `~/.claude/skills/`.\n'
    printf '"Invoked by: you" means the skill only runs when you type its name; "you or agents" means agents can also start it from its description.\n'
    printf 'Owner comes from `.skill-sources.tsv`; see [CONTEXT.md](../CONTEXT.md) for the terms.\n\n'
    printf '| Skill | Invoked by | Owner | What it does |\n'
    printf '| --- | --- | --- | --- |\n'
    local skill_md
    for skill_md in "$SKILLS_DIR"/*/SKILL.md; do
        local dir_name
        dir_name="$(basename "$(dirname "$skill_md")")"
        local name invocation description
        IFS=$'\t' read -r name invocation description < <(frontmatter "$skill_md")
        description="${description//|/\\|}"
        printf '| [`%s`](../stow/claude/.claude/skills/%s/SKILL.md) | %s | %s | %s |\n' \
            "${name:-$dir_name}" "$dir_name" "$invocation" "$(owner_of "$dir_name")" "$description"
    done
}

case "${1:-}" in
    "")
        render > "$CATALOG"
        printf "${GREEN}[skills]${NC} wrote %s\n" "${CATALOG#"$DOTFILES_DIR"/}"
        ;;
    --check)
        if ! diff -u "$CATALOG" <(render) >/dev/null 2>&1; then
            printf "${RED}[skills]${NC} docs/skills.md is out of date; run ./scripts/skill_catalog.sh\n" >&2
            exit 1
        fi
        printf "${GREEN}[skills]${NC} docs/skills.md is up to date\n"
        ;;
    *)
        sed -n '2,5p' "$0" >&2
        exit 2
        ;;
esac
